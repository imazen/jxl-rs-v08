fn bytes(hex: &str) -> Vec<u8> {
    hex.as_bytes()
        .chunks_exact(2)
        .map(|pair| {
            let digit = |v: u8| (v as char).to_digit(16).unwrap() as u8;
            (digit(pair[0]) << 4) | digit(pair[1])
        })
        .collect()
}
#[path = "support/global_squeeze_transposed.rs"]
mod transposed;
fn check(
    encoded: &[u8],
    tile: &[u8],
    width: usize,
    height: usize,
    tile_width: usize,
    tile_height: usize,
) {
    use jxl::api::{
        Event, JxlColorType, JxlDataFormat, JxlDecoder, JxlDecoderOptions, JxlOutputBuffer,
        JxlPixelFormat,
    };
    use jxl::image::{Image, Rect};
    let mut decoder = JxlDecoder::new(JxlDecoderOptions::default());
    let mut input = encoded;
    let mut color: Option<Image<u8>> = None;
    let mut channels = 0;
    let mut frames = 0;
    loop {
        let mut output = color.as_mut().map(|image| {
            let size = image.size();
            vec![JxlOutputBuffer::from_image_rect_mut(
                image
                    .get_rect_mut(Rect {
                        origin: (0, 0),
                        size,
                    })
                    .into_raw(),
            )]
        });
        let event = decoder
            .process(&mut input, output.as_deref_mut(), None)
            .unwrap();
        drop(output);
        match event {
            Event::BasicInfo => {
                assert_eq!(decoder.basic_info().unwrap().size, (width, height));
                let fmt = decoder.current_pixel_format().unwrap().clone();
                assert!(fmt.extra_channel_format.is_empty());
                assert!(fmt.color_type.is_grayscale());
                channels = 2;
                decoder
                    .set_pixel_format(JxlPixelFormat {
                        color_type: JxlColorType::GrayscaleAlpha,
                        color_data_format: Some(JxlDataFormat::U8 { bit_depth: 8 }),
                        extra_channel_format: vec![],
                    })
                    .unwrap();
                color = Some(Image::new((width * channels, height)).unwrap());
            }
            Event::FrameHeader => {}
            Event::FrameComplete { .. } => {
                frames += 1;
                let image = color.as_ref().unwrap();
                assert!(
                    matches!(channels, 1 | 2),
                    "grayscale output channels {channels}"
                );
                for y in 0..height {
                    for (x, pixel) in image.row(y).chunks_exact(channels).enumerate() {
                        assert_eq!(
                            pixel[0],
                            tile[(y % tile_height) * tile_width + x % tile_width],
                            "gray ({x},{y})"
                        );
                        if channels == 2 {
                            assert_eq!(pixel[1], 255, "alpha ({x},{y})");
                        }
                    }
                }
            }
            Event::Complete => {
                assert_eq!(frames, 1);
                return;
            }
            Event::NeedMoreInput { .. } => assert!(!input.is_empty(), "truncated gray fixture"),
        }
    }
}
#[test]
fn global_squeeze_inputs_survive_a_larger_intermediate_channel() {
    check(
        &bytes(STREAM_HEX),
        &bytes(SOURCE_PERIOD_HEX),
        2,
        16449,
        2,
        1105,
    );
}
#[test]
fn transposed_global_squeeze_inputs_preserve_every_source_code() {
    check(
        &bytes(transposed::STREAM_HEX),
        &bytes(transposed::SOURCE_TILE_HEX),
        16449,
        2,
        1118,
        2,
    );
}
